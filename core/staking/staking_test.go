package staking

import (
	"encoding/hex"
	"strings"
	"testing"
)

// TestPrecompileABIMatchesRegisteredMethods is a regression guard for the
// precompile pipeline.
//
// Two files must stay in lockstep:
//
//   - `abi.json` — generated from `core/precompile/contracts/StakingCaller.sol`
//   - the `RegisterMethods` call in `NewPrecompile` — hand-written Go
//
// If they drift, the precompile silently breaks in one of two ways:
//
//   - an ABI function with no Go method -> `method not found in precompile`
//     at call time (this is exactly how `unjail` was shipped broken: it was in
//     the ABI but missing from the Solidity caller, so the regenerated bytecode
//     had no such selector and calls reverted);
//   - a Go method with no ABI entry -> the method is unreachable, because
//     dispatch goes through the ABI's method IDs.
//
// Neither failure is visible to `go build`, so this test is the only automated
// check that the precompile surface is coherent.
func TestPrecompileABIMatchesRegisteredMethods(t *testing.T) {
	// Nil keepers are fine: this only inspects the registered surface, it never
	// executes a method.
	contract, err := NewPrecompile(nil, nil, nil)
	if err != nil {
		t.Fatalf("NewPrecompile: %v", err)
	}

	// Every ABI function must have a registered Go method.
	for name := range contract.Abi.Methods {
		if !contract.HasMethod(name) {
			t.Errorf("ABI function %q has no registered method in NewPrecompile", name)
		}
	}

	// Every registered Go method must exist in the ABI.
	for _, name := range contract.MethodNames() {
		if _, ok := contract.Abi.Methods[name]; !ok {
			t.Errorf("registered method %q is missing from abi.json (unreachable)", name)
		}
	}

	// The methods the staking surface is contracted to expose.
	for _, want := range []string{
		CreateValidatorMethodName,
		DelegateMethodName,
		UndelegateMethodName,
		GetDelegationMethodName,
		UnjailMethodName,
	} {
		if _, ok := contract.Abi.Methods[want]; !ok {
			t.Errorf("expected method %q in abi.json", want)
		}
		if !contract.HasMethod(want) {
			t.Errorf("expected method %q registered in NewPrecompile", want)
		}
	}

	// The deployed bytecode must contain every ABI selector, otherwise
	// `eth_getCode` advertises a contract whose callers revert.
	for name := range contract.Abi.Methods {
		selector := hex.EncodeToString(contract.Abi.Methods[name].ID)
		if !strings.Contains(EvmByteCode, selector) {
			t.Errorf(
				"ABI method %q (selector 0x%s) is absent from EvmByteCode; regenerate with `make precompile-gen`",
				name, selector,
			)
		}
	}
}

// TestCreateValidatorMethodShape pins the ABI signature of createValidator.
//
// The argument order and types are part of the public EVM interface: changing
// them silently breaks every deployed caller and every wallet ABI, so the test
// states them explicitly rather than relying on the generated file alone.
func TestCreateValidatorMethodShape(t *testing.T) {
	contract, err := NewPrecompile(nil, nil, nil)
	if err != nil {
		t.Fatalf("NewPrecompile: %v", err)
	}

	method, ok := contract.Abi.Methods[CreateValidatorMethodName]
	if !ok {
		t.Fatalf("method %q missing from ABI", CreateValidatorMethodName)
	}

	wantTypes := []string{
		"bytes", "uint256", "string", "uint256", "uint256", "uint256", "uint256",
	}
	if len(method.Inputs) != len(wantTypes) {
		t.Fatalf("createValidator has %d inputs, want %d", len(method.Inputs), len(wantTypes))
	}
	for i, want := range wantTypes {
		if got := method.Inputs[i].Type.String(); got != want {
			t.Errorf("createValidator input %d type = %q, want %q", i, got, want)
		}
	}

	if len(method.Outputs) != 1 || method.Outputs[0].Type.String() != "bool" {
		t.Errorf("createValidator must return a single bool, got %v", method.Outputs)
	}
}
